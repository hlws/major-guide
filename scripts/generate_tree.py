def fm(items):
    """输出 YAML front matter，供 CI 与贡献者填写。"""
    lines = ["---"] + [f"{k}: {v}" for k, v in items] + ["---", ""]
    return "\n".join(lines) + "\n"

BAD = '\\/:*?"<>|'


def safe(name):
    n = name.strip()
    for ch in BAD:
        n = n.replace(ch, "·")
    return n


